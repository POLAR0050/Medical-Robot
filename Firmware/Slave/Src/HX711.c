#include <util/delay.h>

#include "HX711.h"
#include "DIO.h"

#define SCK_PORT PORTC_ID
#define SCK_PIN  PIN4

#define DT_PORT  PORTC_ID
#define DT_PIN   PIN5

void HX711_Init(void)
{
	DIO_SetPinDirection(SCK_PORT, SCK_PIN, PIN_OUTPUT);
	DIO_SetPinValue(SCK_PORT, SCK_PIN, PIN_LOW);

	DIO_SetPinDirection(DT_PORT, DT_PIN, PIN_INPUT);
}

u8 HX711_IsReady(void)
{
	/* HX711 ????? ??? ??? DT ?? LOW ??? ???? ??? ????? ????? */
	return (DIO_GetPinValue(DT_PORT, DT_PIN) == PIN_LOW) ? 1 : 0;
}

s32 HX711_ReadRaw(void)
{
	u32 value = 0;
	u8 i;

	/* ????? ??? ?? ???? ??? ????? ????? */
	while(HX711_IsReady() == 0);

	/* ???? ??? 24 ?? (MSB ?????) */
	for(i = 0; i < 24; i++)
	{
		DIO_SetPinValue(SCK_PORT, SCK_PIN, PIN_HIGH);
		_delay_us(1);

		value = value << 1;

		DIO_SetPinValue(SCK_PORT, SCK_PIN, PIN_LOW);
		_delay_us(1);

		if(DIO_GetPinValue(DT_PORT, DT_PIN) == PIN_HIGH)
		{
			value |= 1;
		}
	}

	/* ?????? ??? 25 - ????? ??? Gain ??? 128 ????? A (????? ?????????) */
	DIO_SetPinValue(SCK_PORT, SCK_PIN, PIN_HIGH);
	_delay_us(1);
	DIO_SetPinValue(SCK_PORT, SCK_PIN, PIN_LOW);
	_delay_us(1);

	/* ????? ??????? (Sign Extension) ?? 24-bit ?? 32-bit */
	if(value & 0x800000UL)
	{
		value |= 0xFF000000UL;
	}

	return (s32)value;
}
