#define TRAVEL_SPEED       50   /* ???? ?????? ????? ??????? (0-100) */
#define SAFE_DISTANCE_CM   10   /* ?? ??????? ??? ?? ??? -> ??? ????? */
#define TRAVEL_TIMEOUT_MS  15000UL   /* ???? ??? ?????? ??? ?? ??????? ???? */

#define MISSION_SUCCESS 1
#define MISSION_ERROR   0

void SLAVE_Init(void)
{
	UART_Init();
	MOTOR_Init();
	SERVO_Init();
	ULTRASONIC_Init();
	LM35_Init();
	LINE_SENSOR_Init();
	LIMIT_SWITCH_Init();
	LED_Init();
	BUZZER_Init();
	HX711_Init();

	SERVO_SetAngle(0);   /* ????? ????? ?? ??????? */
}

void SLAVE_WaitCommand(u16 *Room, u8 *Medicine)
{
	u8 room_high;
	u8 room_low;
	u8 med;
	u8 start_flag;

	/* ??????? ?? ?? ??????? ?????? ?????? */
	room_high = UART_ReceiveChar();
	room_low  = UART_ReceiveChar();
	med       = UART_ReceiveChar();
	start_flag = UART_ReceiveChar();

	if(start_flag == 'S')
	{
		*Room = ((u16)room_high << 8) | room_low;
		*Medicine = med;
	}
	else
	{
		*Room = 0;
		*Medicine = 0;
	}
}

static void SLAVE_OpenCompartment(void)
{
	u8 i;

	/* ???? ?????? ??? ??? ???? ??????? ???? ???? ????? ????? ???? ???? */
	for(i = 0; i < 15; i++)
	{
		SERVO_SetAngle(90);
		_delay_ms(20);
	}
}

static void SLAVE_CloseCompartment(void)
{
	u8 i;

	for(i = 0; i < 15; i++)
	{
		SERVO_SetAngle(0);
		_delay_ms(20);
	}
}

static u8 SLAVE_TravelToRoom(void)
{
	u16 distance;
	u32 elapsed_ms = 0;

	MOTOR_Forward(TRAVEL_SPEED);

	while(1)
	{
		distance = ULTRASONIC_GetDistance();

		/* ?? ???? ???? ???? -> ??? ????? (????) */
		if(distance != 0 && distance < SAFE_DISTANCE_CM)
		{
			MOTOR_Stop();
			return MISSION_ERROR;
		}

		/* ??? ?????? (??????? ?????) */
		if(LIMIT_SWITCH_IsPressed())
		{
			MOTOR_Stop();
			return MISSION_SUCCESS;
		}

		_delay_ms(50);
		elapsed_ms += 50;

		/* ???? ??? ???? ?? ???? ??????? ???? */
		if(elapsed_ms > TRAVEL_TIMEOUT_MS)
		{
			MOTOR_Stop();
			return MISSION_ERROR;
		}
	}
}

u8 SLAVE_ExecuteMission(u16 Room, u8 Medicine)
{
	u8 travel_result;

	(void)Room;       /* ?????? ?????? ?????? ??? ?? ???? ???????? ?????? */
	(void)Medicine;   /* (?? ????? ??? ???? ?? ?????? ???? ????) */

	LED_On();

	travel_result = SLAVE_TravelToRoom();

	if(travel_result == MISSION_ERROR)
	{
		LED_Off();
		return MISSION_ERROR;
	}

	SLAVE_OpenCompartment();

	BUZZER_On();
	_delay_ms(500);
	BUZZER_Off();

	_delay_ms(3000);   /* ??? ???? ?? ???? ????? */

	SLAVE_CloseCompartment();

	LED_Off();

	return MISSION_SUCCESS;
}

void SLAVE_SendResult(u8 result)
{
	if(result == MISSION_SUCCESS)
	{
		UART_SendChar('K');
	}
	else
	{
		UART_SendChar('E');
	}
}
