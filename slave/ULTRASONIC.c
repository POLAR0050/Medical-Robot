#include <util/delay.h>

#include "ULTRASONIC.h"
#include "DIO.h"

#define TRIGGER_PORT PORTC_ID
#define TRIGGER_PIN  PIN0

#define ECHO_PORT    PORTD_ID
#define ECHO_PIN     PIN2

#define TIMEOUT_LOOPS 40000UL   /* ?? ???? ???????? ???? ????? ?????? ?? ?????? ?? ????? */

void ULTRASONIC_Init(void)
{
	DIO_SetPinDirection(TRIGGER_PORT, TRIGGER_PIN, PIN_OUTPUT);
	DIO_SetPinValue(TRIGGER_PORT, TRIGGER_PIN, PIN_LOW);

	DIO_SetPinDirection(ECHO_PORT, ECHO_PIN, PIN_INPUT);
}

u16 ULTRASONIC_GetDistance(void)
{
	u32 timeout;
	u32 pulse_us;
	u16 distance;

	/* ??? ???? Trigger ???? 10 ?????????? */
	DIO_SetPinValue(TRIGGER_PORT, TRIGGER_PIN, PIN_HIGH);
	_delay_us(10);
	DIO_SetPinValue(TRIGGER_PORT, TRIGGER_PIN, PIN_LOW);

	/* ????? ??? Echo ???? HIGH (????? ?????? ???????) */
	timeout = 0;
	while(DIO_GetPinValue(ECHO_PORT, ECHO_PIN) == PIN_LOW)
	{
		timeout++;
		if(timeout > TIMEOUT_LOOPS)
		{
			return 0;   /* ???? ?? - ?????? ?? ????? ?? ???? ???? ???? */
		}
	}

	/* ??? ????????????? ??? ?? ??? Echo ??? HIGH (Loop-based? ?? ??? Timer ???????) */
	pulse_us = 0;
	while(DIO_GetPinValue(ECHO_PORT, ECHO_PIN) == PIN_HIGH)
	{
		_delay_us(1);
		pulse_us++;

		if(pulse_us > TIMEOUT_LOOPS)
		{
			return 0;
		}
	}

	/* ?????? HC-SR04 ????????: ??????? (??) = ??? ?????? / 58 */
	distance = (u16)(pulse_us / 58);

	return distance;
}